// # 이 파일에는 화면이 없다. 데이터의 모양만 적어둔다.
// ==================================================================

// # [명령어] export type Member = { ... };
// # 구조: "type Member"는 Member라는 이름의 약속(양식)을 만든다.
// #       "= { ... }" 안에는 칸 이름과 칸에 들어갈 자료형을 "칸이름: 자료형" 순서로 적는다.
// #       "export"는 이 약속을 다른 파일에서도 가져다 쓸 수 있게 내보낸다.
// # 목적: MemberCard, MemberList, page.tsx가 모두 같은 양식으로 회원을 다루게 한다.
// # 예상결과: 저장해도 브라우저 화면은 변하지 않는다. (약속만 만들었을 뿐 화면은 안 건드렸다)
export type Member = {
  // # member_id: number
  // # 구조: "칸이름: 자료형". number는 숫자만 넣을 수 있다.
  // # 목적: 회원마다 겹치지 않는 번호(주민번호 같은 고유 번호)
  // # 예상결과: member_id: 1 은 가능, member_id: "일" 은 빨간 줄(오류)
  member_id: number;

  // # name: string
  // # 구조: string은 글자(문자열)만 넣을 수 있다. 글자는 따옴표 "" 로 감싼다.
  // # 예상결과: name: "Kim" 은 가능, name: 123 은 오류
  name: string;

  // # email: string
  // # 예상결과: email: "kim@example.com" 처럼 글자로 입력
  email: string;

  // # age: number
  // # 예상결과: age: 30 은 가능, age: "thirty" 는 오류 (STEP 07에서 일부러 오류를 만들어 본다)
  age: number;
};