#두개의 숫자를 입력 받아서 합계를 출력 하는 프로그램 작성

first_num = input("첫 번째 숫자를 입력하세요:")  #first_num = int(input("첫 번째 숫자를 입력하세요:"))
second_num = input("두 번째 숫자를 입력하세요:")

full_num = (int(first_num) + int(second_num))  #튜터님 >>> result = first_num + second_num

print(f"두 숫자의 합은, {full_num}입니다")   #튜터님 >>> print(f"{first_num} 더하기 {second_num}는 {result}입니다~") _ 잘못된 예시로



